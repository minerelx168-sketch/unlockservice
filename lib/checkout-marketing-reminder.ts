/**
 * DRAFT: one post-checkout marketing reminder, deliberately isolated from
 * transactional checkout-link mail. Production adapters are intentionally not
 * included here; see the port comments before wiring SQLite/Whop/Resend.
 */

export const REMINDER_DELAY_MS = 5 * 60 * 1000
export const MAX_REMINDER_ATTEMPTS = 3
export const MAX_REMINDERS = 1
const IDEMPOTENCY_LIFETIME_MS = 23 * 60 * 60 * 1000 // below a 24h provider window
const LEASE_MS = 10 * 60 * 1000
const RETRY_BACKOFF_MS = [5 * 60 * 1000, 30 * 60 * 1000] as const

export type MarketingConsent = {
  verified: true
  source: 'explicit_checkout_opt_in'
  verifiedAtMs: number
}

export type CheckoutMarketingRecord = {
  billId: string
  accountId: string
  planId: string
  hostedCheckoutId: string
  /** A real, saved card-hosted checkout URL; crypto URLs are never eligible. */
  hostedCheckoutUrl: string | null
  /** Signed private application URL, not a provider URL. */
  appCheckoutUrl: string
  /** Signed unsubscribe URL generated by the application. */
  unsubscribeUrl: string
  paymentMethod: 'card' | 'crypto'
  websiteCheckoutEmail: string
  serviceName: string
  checkoutCreatedAtMs: number
  checkoutExpiresAtMs: number
  /** Both values are persisted independently so the adapter can verify the card quote. */
  quoteCurrency: string
  quoteTotalMinor: number
  cardCurrency: string
  cardTotalMinor: number
  marketingConsent: MarketingConsent | null
  /** Opaque, non-PII keys made by the store; never derive them from raw email/IMEI here. */
  recipientKey: string
  dedupeKey: string
}

export type CheckoutPaymentState = 'pending' | 'paid' | 'review' | 'expired' | 'refunded'

export type CheckoutMarketingState = {
  paymentState: CheckoutPaymentState
  marketingSuppressed: boolean
}

export type GatewayVerificationInput = {
  billId: string
  accountId: string
  planId: string
  hostedCheckoutId: string
  currency: string
  totalMinor: number
}

export type GatewayVerdict =
  | ({ kind: 'confirmed_unpaid' } & GatewayVerificationInput)
  | { kind: 'paid' | 'review' | 'expired' | 'not_found' | 'ambiguous' | 'network_error' | 'mismatch' }

export type CheckoutMarketingEmail = {
  to: string
  from: string
  replyTo: string
  subject: 'Complete your iUnlockMobile checkout'
  html: string
  text: string
  idempotencyKey: string
  headers: {
    'List-Unsubscribe': string
    'List-Unsubscribe-Post': 'List-Unsubscribe=One-Click'
  }
}

export type MarketingSendResult =
  | { kind: 'accepted'; providerMessageId: string }
  /** Only use this when the transport knows the provider did not accept it. */
  | { kind: 'not_accepted'; reason: string; retryable?: boolean }
  /** Unknown/timeout outcomes are never safe to retry automatically. */
  | { kind: 'ambiguous'; reason: string }

export type ClaimReminderInput = {
  billId: string
  recipientKey: string
  dedupeKey: string
  idempotencyKey: string
  nowMs: number
  leaseUntilMs: number
  idempotencyValidUntilMs: number
  maxAttempts: typeof MAX_REMINDER_ATTEMPTS
  maxReminders: typeof MAX_REMINDERS
}

export type ReminderClaim =
  | { kind: 'claimed'; leaseToken: string; attempt: number }
  | {
      kind: 'skipped'
      reason: 'already_sent' | 'deduplicated' | 'active_lease' | 'attempt_limit' | 'unresolved' | 'suppressed' | 'paid' | 'expired' | 'unavailable'
    }

/**
 * Persistent adapter contract. `claimReminder` must be one atomic database
 * operation: lease only a still-pending row, enforce MAX_REMINDERS/attempt
 * bounds, and enforce uniqueness across paid/other campaigns for the same
 * recipientKey + dedupeKey (recipient/service/device), not just this bill.
 *
 * The adapter must re-check paid/suppressed state while claiming and while
 * recording accepted mail. A lease token is compare-and-set: a stale lease
 * never overwrites a newer lease or accepted provider message. There is no
 * release method by design. Ambiguous transport stays claimed/unresolved and
 * must not rotate its idempotency key or be blindly retried.
 */
export interface CheckoutMarketingStore {
  getCheckout(billId: string): Promise<CheckoutMarketingRecord | null>
  readCurrentState(billId: string): Promise<CheckoutMarketingState | null>
  claimReminder(input: ClaimReminderInput): Promise<ReminderClaim>
  recordAccepted(input: {
    billId: string
    leaseToken: string
    idempotencyKey: string
    providerMessageId: string
    sentAtMs: number
  }): Promise<'recorded' | 'stale_lease' | 'already_recorded'>
  recordNotAccepted(input: {
    billId: string
    leaseToken: string
    idempotencyKey: string
    attempt: number
    nextAttemptAtMs: number | null
    recordedAtMs: number
  }): Promise<void>
  recordAmbiguous(input: {
    billId: string
    leaseToken: string
    idempotencyKey: string
    unresolvedAtMs: number
    reason: string
  }): Promise<void>
}

/** The adapter must verify the same bill/account/plan and captured card total. */
export interface AuthoritativeCheckoutGateway {
  verifyPendingCheckout(input: GatewayVerificationInput): Promise<GatewayVerdict>
}

/** Resend-specific fetch/SDK code belongs in this injected adapter, never here. */
export interface MarketingEmailSender {
  sendMarketingEmail(message: CheckoutMarketingEmail): Promise<MarketingSendResult>
}

export type CheckoutMarketingConfig = {
  /** Opt-in is exact; absent/false is disabled. */
  enabled?: boolean
  senderBusinessName: string
  senderPostalAddress: string
  senderEmail: string
  replyTo: string
  publicOrigin: string
}

export type CheckoutMarketingDependencies = {
  store: CheckoutMarketingStore
  gateway: AuthoritativeCheckoutGateway
  mailer: MarketingEmailSender
}

export type ReminderOutcome =
  | { kind: 'disabled' | 'skipped'; reason: string }
  | { kind: 'sent'; providerMessageId: string; recorded: boolean; idempotencyKey: string }
  | { kind: 'retry_scheduled'; attempt: number; retryAtMs: number; idempotencyKey: string }
  | { kind: 'not_accepted_exhausted'; attempt: number; idempotencyKey: string }
  | { kind: 'ambiguous'; idempotencyKey: string }

const REF_RE = /^[A-Za-z0-9][A-Za-z0-9._:-]{0,95}$/
const OPAQUE_KEY_RE = /^[A-Za-z0-9_-]{16,128}$/
const EMAIL_RE = /^[^\s@<>]+@[^\s@<>]+\.[^\s@<>]+$/

function validRef(value: unknown): value is string {
  return typeof value === 'string' && REF_RE.test(value)
}

function skip(reason: string): ReminderOutcome {
  return { kind: 'skipped', reason }
}

function finiteMs(value: number): boolean {
  return Number.isSafeInteger(value) && value >= 0
}

function validText(value: unknown, max: number): value is string {
  return typeof value === 'string' && value.trim().length > 0 && value.length <= max && !/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/.test(value)
}

function validEmail(value: unknown): value is string {
  return typeof value === 'string' && value.length <= 254 && EMAIL_RE.test(value) && value === value.trim()
}

function appOrigin(value: unknown): string | null {
  if (typeof value !== 'string') return null
  try {
    const url = new URL(value)
    if (url.protocol !== 'https:' || url.username || url.password || url.pathname !== '/' || url.search || url.hash) return null
    return url.origin
  } catch {
    return null
  }
}

function appUrl(value: unknown, origin: string): value is string {
  if (typeof value !== 'string') return false
  try {
    const url = new URL(value)
    return url.protocol === 'https:' && url.origin === origin && !url.username && !url.password && url.pathname !== '/' && !/[\r\n]/.test(value)
  } catch {
    return false
  }
}

function hostedUrl(value: unknown): value is string {
  if (typeof value !== 'string' || !value) return false
  try {
    const url = new URL(value)
    return url.protocol === 'https:' && !url.username && !url.password && url.pathname !== '/' && !/[\r\n]/.test(value)
  } catch {
    return false
  }
}

function canonicalEmail(value: unknown): string | null {
  if (typeof value !== 'string') return null
  const normalized = value.trim().toLowerCase()
  return validEmail(normalized) ? normalized : null
}

function validRecord(record: CheckoutMarketingRecord, billId: string, nowMs: number, origin: string): boolean {
  const consent = record.marketingConsent
  return record.billId === billId && validRef(record.billId) && validRef(record.accountId) && validRef(record.planId)
    && validRef(record.hostedCheckoutId) && record.paymentMethod === 'card' && hostedUrl(record.hostedCheckoutUrl)
    && canonicalEmail(record.websiteCheckoutEmail) !== null && validText(record.serviceName, 160)
    && finiteMs(record.checkoutCreatedAtMs) && finiteMs(record.checkoutExpiresAtMs)
    && record.checkoutExpiresAtMs > record.checkoutCreatedAtMs && nowMs >= record.checkoutCreatedAtMs && nowMs < record.checkoutExpiresAtMs
    && /^[A-Z]{3}$/.test(record.quoteCurrency) && record.quoteCurrency === record.cardCurrency
    && Number.isSafeInteger(record.quoteTotalMinor) && record.quoteTotalMinor > 0
    && Number.isSafeInteger(record.cardTotalMinor) && record.cardTotalMinor > 0
    && appUrl(record.appCheckoutUrl, origin) && appUrl(record.unsubscribeUrl, origin)
    && OPAQUE_KEY_RE.test(record.recipientKey) && OPAQUE_KEY_RE.test(record.dedupeKey)
    && consent?.verified === true && consent.source === 'explicit_checkout_opt_in'
    && finiteMs(consent.verifiedAtMs) && consent.verifiedAtMs >= record.checkoutCreatedAtMs && consent.verifiedAtMs <= nowMs
}

function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, (character) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[character]!)
}

function money(currency: string, minor: number): string {
  return `${currency} ${(minor / 100).toFixed(2)}`
}

function renderEmail(record: CheckoutMarketingRecord, config: CheckoutMarketingConfig, idempotencyKey: string): CheckoutMarketingEmail {
  const to = canonicalEmail(record.websiteCheckoutEmail)!
  const service = escapeHtml(record.serviceName.trim())
  const total = money(record.cardCurrency, record.cardTotalMinor)
  const business = escapeHtml(config.senderBusinessName.trim())
  const address = escapeHtml(config.senderPostalAddress.trim())
  const checkout = escapeHtml(record.appCheckoutUrl)
  const unsubscribe = escapeHtml(record.unsubscribeUrl)
  const text = [
    'Marketing reminder',
    '',
    `You started a checkout for ${record.serviceName.trim()}.`,
    `Your saved card total is ${total}.`,
    '',
    `Continue securely: ${record.appCheckoutUrl}`,
    '',
    'Already paid? Open your private link to check your status and do not pay again.',
    'We will not send another marketing reminder for this checkout.',
    `Need help? Contact ${config.replyTo}.`,
    '',
    'This is a marketing reminder. If you no longer want these reminders, unsubscribe here:',
    record.unsubscribeUrl,
    '',
    config.senderBusinessName.trim(),
    config.senderPostalAddress.trim(),
  ].join('\n')
  const html = `<div style="font-family:system-ui,sans-serif;max-width:560px;margin:auto;padding:32px"><p style="font-size:12px;text-transform:uppercase;letter-spacing:.08em">Marketing reminder</p><h1>Complete your iUnlockMobile checkout</h1><p>You started a checkout for <strong>${service}</strong>.</p><p>Your saved card total is <strong>${escapeHtml(total)}</strong>.</p><p><a href="${checkout}">Continue secure checkout</a></p><p>Already paid? Open your private link to check your status and do not pay again. We will not send another marketing reminder for this checkout.</p><p>Need help? Contact ${escapeHtml(config.replyTo)}.</p><p>If you no longer want these reminders, <a href="${unsubscribe}">unsubscribe</a>.</p><hr><p>${business}<br>${address}</p></div>`
  return {
    to,
    from: `${config.senderBusinessName.trim()} <${config.senderEmail}>`,
    replyTo: config.replyTo,
    subject: 'Complete your iUnlockMobile checkout',
    html,
    text,
    idempotencyKey,
    headers: {
      'List-Unsubscribe': `<${record.unsubscribeUrl}>`,
      'List-Unsubscribe-Post': 'List-Unsubscribe=One-Click',
    },
  }
}

function sameVerification(record: CheckoutMarketingRecord, verdict: GatewayVerdict): boolean {
  return verdict.kind === 'confirmed_unpaid' && verdict.billId === record.billId && verdict.accountId === record.accountId
    && verdict.planId === record.planId && verdict.hostedCheckoutId === record.hostedCheckoutId
    && verdict.currency === record.cardCurrency && verdict.totalMinor === record.cardTotalMinor
}

/**
 * Evaluate one bill. This function has no network client, SDK, secret, crypto,
 * logging, production store, or automatic claim release. Parent integration
 * should call it from a bounded worker after implementing the three ports.
 */
export async function maybeSendCheckoutMarketingReminder(
  billId: string,
  config: CheckoutMarketingConfig,
  dependencies: CheckoutMarketingDependencies,
  nowMs = Date.now(),
): Promise<ReminderOutcome> {
  if (config.enabled !== true) return { kind: 'disabled', reason: 'feature_disabled' }
  if (!finiteMs(nowMs)) return skip('invalid_time')
  const origin = appOrigin(config.publicOrigin)
  if (!origin || !validText(config.senderBusinessName, 160) || !validText(config.senderPostalAddress, 500)
    || /[\r\n]/.test(config.senderBusinessName)
    || !validEmail(config.senderEmail) || !validEmail(config.replyTo) || !REF_RE.test(billId)) return skip('invalid_config_or_bill')

  let record: CheckoutMarketingRecord | null
  try {
    record = await dependencies.store.getCheckout(billId)
  } catch {
    return skip('store_error')
  }
  if (!record || !validRecord(record, billId, nowMs, origin)) return skip('not_eligible')
  if (nowMs - record.checkoutCreatedAtMs < REMINDER_DELAY_MS || nowMs >= record.checkoutCreatedAtMs + IDEMPOTENCY_LIFETIME_MS) return skip('outside_reminder_window')

  let state: CheckoutMarketingState | null
  try {
    state = await dependencies.store.readCurrentState(billId)
  } catch {
    return skip('state_error')
  }
  if (!state || state.paymentState !== 'pending' || state.marketingSuppressed) return skip('state_not_pending_or_suppressed')

  const verificationInput: GatewayVerificationInput = {
    billId: record.billId,
    accountId: record.accountId,
    planId: record.planId,
    hostedCheckoutId: record.hostedCheckoutId,
    currency: record.cardCurrency,
    totalMinor: record.cardTotalMinor,
  }
  let verdict: GatewayVerdict
  try {
    verdict = await dependencies.gateway.verifyPendingCheckout(verificationInput)
  } catch {
    return skip('gateway_error')
  }
  if (!sameVerification(record, verdict)) return skip('gateway_not_confirmed_unpaid')

  // Re-read after provider verification: payment/suppression changes win over a stale check.
  try {
    state = await dependencies.store.readCurrentState(billId)
  } catch {
    return skip('state_error_after_gateway')
  }
  if (!state || state.paymentState !== 'pending' || state.marketingSuppressed) return skip('state_changed_before_send')

  const idempotencyKey = `checkout-marketing-reminder:${record.billId}`
  const idempotencyValidUntilMs = Math.min(record.checkoutCreatedAtMs + IDEMPOTENCY_LIFETIME_MS, record.checkoutExpiresAtMs)
  if (nowMs >= idempotencyValidUntilMs) return skip('idempotency_window_closed')
  const email = renderEmail(record, config, idempotencyKey)

  let claim: ReminderClaim
  try {
    claim = await dependencies.store.claimReminder({
      billId,
      recipientKey: record.recipientKey,
      dedupeKey: record.dedupeKey,
      idempotencyKey,
      nowMs,
      leaseUntilMs: Math.min(nowMs + LEASE_MS, idempotencyValidUntilMs),
      idempotencyValidUntilMs,
      maxAttempts: MAX_REMINDER_ATTEMPTS,
      maxReminders: MAX_REMINDERS,
    })
  } catch {
    return skip('claim_error')
  }
  if (claim.kind === 'skipped') return skip(`claim_${claim.reason}`)
  if (!OPAQUE_KEY_RE.test(claim.leaseToken) || !Number.isInteger(claim.attempt) || claim.attempt < 1 || claim.attempt > MAX_REMINDER_ATTEMPTS) return skip('invalid_claim')

  let sendResult: MarketingSendResult
  try {
    sendResult = await dependencies.mailer.sendMarketingEmail(email)
  } catch {
    try {
      await dependencies.store.recordAmbiguous({ billId, leaseToken: claim.leaseToken, idempotencyKey, unresolvedAtMs: nowMs, reason: 'transport_exception' })
    } catch {
      // The claim remains unresolved; never release or rotate it after uncertainty.
    }
    return { kind: 'ambiguous', idempotencyKey }
  }

  if (sendResult.kind === 'accepted' && REF_RE.test(sendResult.providerMessageId)) {
    let recorded = false
    try {
      recorded = (await dependencies.store.recordAccepted({ billId, leaseToken: claim.leaseToken, idempotencyKey, providerMessageId: sendResult.providerMessageId, sentAtMs: nowMs })) === 'recorded'
    } catch {
      // The provider accepted; a failed durable write must not trigger a second send.
    }
    return { kind: 'sent', providerMessageId: sendResult.providerMessageId, recorded, idempotencyKey }
  }

  if (sendResult.kind === 'not_accepted') {
    const backoff = RETRY_BACKOFF_MS[claim.attempt - 1]
    const retryAtMs = sendResult.retryable === false || backoff === undefined ? null : nowMs + backoff < idempotencyValidUntilMs ? nowMs + backoff : null
    try {
      await dependencies.store.recordNotAccepted({ billId, leaseToken: claim.leaseToken, idempotencyKey, attempt: claim.attempt, nextAttemptAtMs: retryAtMs, recordedAtMs: nowMs })
    } catch {
      return skip('not_accepted_state_error')
    }
    return retryAtMs === null
      ? { kind: 'not_accepted_exhausted', attempt: claim.attempt, idempotencyKey }
      : { kind: 'retry_scheduled', attempt: claim.attempt, retryAtMs, idempotencyKey }
  }

  try {
    await dependencies.store.recordAmbiguous({
      billId,
      leaseToken: claim.leaseToken,
      idempotencyKey,
      unresolvedAtMs: nowMs,
      reason: sendResult.kind === 'ambiguous' ? sendResult.reason : 'invalid_transport_result',
    })
  } catch {
    // Keep the durable claim unresolved rather than attempting another send.
  }
  return { kind: 'ambiguous', idempotencyKey }
}
